const assert = require('node:assert/strict');
const path = require('node:path');
const {chromium} = require(process.env.GRIDLAB_PLAYWRIGHT || 'playwright');
(async()=>{
  const browser=await chromium.launch({headless:true,executablePath:process.env.GRIDLAB_CHROMIUM});
  const page=await browser.newPage({viewport:{width:1440,height:1150},deviceScaleFactor:1});
  const errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto('http://localhost:8765');
  await page.getByText('Engine ready',{exact:true}).waitFor({timeout:90000});
  await page.waitForFunction(()=>document.querySelector('#customers').textContent==='732');
  await page.waitForFunction(()=>document.querySelector('#interval').disabled===false);
  const model=await (await page.request.get('http://localhost:8765/api/network')).json();
  assert.equal(model.customer_count_metadata,732);
  assert.equal(model.load_objects,1329);
  await page.locator('#search').fill(model.elements.find(e=>e.kind==='transformer').id);
  await page.locator('#find').click();
  await page.getByText('Winding 1',{exact:true}).waitFor();
  await page.locator('#layer').selectOption('loading');
  await page.locator('#interval').fill('20');
  await page.waitForFunction(()=>snap?.index===20);
  const before=await page.evaluate(()=>camera.scale);
  await page.locator('#network').hover();
  await page.mouse.wheel(0,-200);
  assert(await page.evaluate(()=>camera.scale)>before);
  await page.locator('#reset-view').click();
  const point=await page.evaluate(()=>({p:positions.get(net.source_bus),id:net.source_bus}));
  const box=await page.locator('#network').boundingBox();
  await page.mouse.click(box.x+point.p.x,box.y+point.p.y);
  await page.waitForFunction(id=>document.querySelector('.selected-name').textContent===id,point.id);
  await page.locator('[data-tab="logs"]').click();
  await page.locator('#log-lines .log-entry').first().waitFor();
  await page.locator('#log-lines details').first().locator('summary').click();
  await page.locator('[data-tab="diagnostics"]').click();
  const invalid=await page.request.post('http://localhost:8765/api/runs',{data:{date:'2019-01-01',days:1}});
  assert.equal(invalid.status(),422);
  const cors=await page.request.post('http://localhost:8765/api/runs',{headers:{Origin:'https://unrelated.example'},data:{date:'2018-01-01',days:1}});
  assert.equal(cors.status(),403);
  await page.locator('#date').fill('2018-07-01');
  await page.locator('#run').click();
  await page.waitForFunction(()=>job?.date==='2018-07-01'&&job?.status==='running');
  const busy=await page.request.post('http://localhost:8765/api/runs',{data:{date:'2018-01-01',days:1}});
  assert.equal(busy.status(),409);
  await page.waitForFunction(()=>job?.date==='2018-07-01'&&job?.status==='completed',{timeout:90000});
  assert.equal(await page.evaluate(()=>job.completed),96);
  assert.equal(await page.evaluate(()=>job.totals.balance_failures),0);
  await page.locator('#interval').fill('48');
  await page.waitForFunction(()=>snap?.index===48);
  await page.locator('#export').click({trial:true});
  await page.screenshot({path:path.join(__dirname,'..','runs','dashboard-desktop.png'),fullPage:true});
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:path.join(__dirname,'..','runs','dashboard-mobile.png'),fullPage:true});
  const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1);
  assert.equal(overflow,false,'Mobile viewport should not overflow horizontally');
  assert.deepEqual(errors,[]);
  console.log(JSON.stringify({passed:true,buses:model.bus_count,loadObjects:model.load_objects,browserErrors:errors,run:await page.evaluate(()=>({id:job.id,status:job.status,totals:job.totals}))},null,2));
  await browser.close();
})().catch(e=>{console.error(e);process.exit(1);});