const assert=require('node:assert/strict');
const path=require('node:path');
const {chromium}=require(process.env.GRIDLAB_PLAYWRIGHT||'playwright');
(async()=>{
  const browser=await chromium.launch({headless:true,executablePath:process.env.GRIDLAB_CHROMIUM});
  try{
    const page=await browser.newPage({viewport:{width:1500,height:1120},deviceScaleFactor:1});
    const errors=[];page.on('pageerror',e=>errors.push(e.message));
    await page.goto('http://localhost:8765');
    await page.waitForFunction(()=>fleet?.summary.ev_count===75&&!document.querySelector('#fleet-generate').disabled,{timeout:90000});
    assert.equal(await page.locator('#fleet-households').textContent(),'447');
    assert.equal(await page.locator('#fleet-vehicles').textContent(),'751');
    assert.equal(await page.locator('#fleet-evs').textContent(),'75');
    assert((await page.locator('#fleet-storage').textContent()).includes('5,695'));
    const defaultFleet=await page.evaluate(()=>fleet.id);
    const originalNetwork=(await (await page.request.get('http://localhost:8765/api/network')).json());
    const initialRuns=await(await page.request.get('http://localhost:8765/api/runs')).json();
    await page.locator('#layer').selectOption('fleet');
    const markerCount=await page.evaluate(()=>fleetMarkers().length);
    assert.equal(markerCount,await page.evaluate(()=>new Set(fleet.households.filter(h=>h.ev_count>0).map(h=>h.bus)).size));
    assert.equal(await page.evaluate(()=>fleetMarkers().reduce((n,m)=>n+m.count,0)),75);
    await page.locator('#fleet-household-rows button').first().click();
    await page.waitForFunction(()=>document.querySelector('.fleet-inspector-title')?.textContent==='Household vehicle inventory');
    assert(await page.locator('.vehicle-card').count()>0);
    const inspectedBus=await page.evaluate(()=>selected.id);
    assert(await page.evaluate(bus=>fleetByBus.has(bus),inspectedBus));
    await page.locator('#fleet-generate').click();
    await page.waitForFunction(()=>!fleetBusy);
    assert.equal(await page.evaluate(()=>fleet.id),defaultFleet);
    await page.locator('#fleet-adoption').fill('20');await page.locator('#fleet-generate').click();
    await page.waitForFunction(()=>fleet?.summary.ev_count===150&&!fleetBusy);
    await page.locator('#fleet-mode').selectOption('fixed');
    await page.locator('#fleet-count').fill('500');await page.locator('#fleet-generate').click();
    await page.waitForFunction(()=>fleet?.summary.ev_count===500&&!fleetBusy);
    const invalid=await page.request.post('http://localhost:8765/api/fleets',{data:{mode:'fixed',fixed_ev_count:752}});
    assert.equal(invalid.status(),422);
    await page.locator('#fleet-mode').selectOption('adoption');await page.locator('#fleet-adoption').fill('10');
    await page.locator('#fleet-seed').fill('43');await page.locator('#fleet-generate').click();
    await page.waitForFunction(()=>fleet?.config.seed===43&&!fleetBusy);
    assert.notEqual(await page.evaluate(()=>fleet.id),defaultFleet);
    await page.locator('#fleet-seed').fill('42');
    await page.getByText('Allocation assumptions & service audit',{exact:true}).click();
    await page.locator('#fleet-home-access').fill('100');await page.locator('#fleet-level1').fill('100');
    await page.locator('#fleet-generate').click();
    await page.waitForFunction(()=>fleet?.summary.level1_count===75&&!fleetBusy);
    assert.equal(await page.evaluate(()=>fleet.summary.potential_home_charging_kw),108);
    await page.locator('#fleet-home-access').fill('75');await page.locator('#fleet-level1').fill('20');
    await page.locator('#fleet-generate').click();await page.waitForFunction(id=>fleet?.id===id&&!fleetBusy,defaultFleet);
    const exported=await(await page.request.get('http://localhost:8765/api/fleets/'+defaultFleet+'/export')).json();
    assert.equal(exported.id,defaultFleet);assert.equal(exported.vehicles.filter(v=>v.is_ev).length,75);
    const afterNetwork=await(await page.request.get('http://localhost:8765/api/network')).json();
    assert.deepEqual(afterNetwork,originalNetwork,'Fleet generation must not alter the electrical model');
    const afterRuns=await(await page.request.get('http://localhost:8765/api/runs')).json();
    assert.deepEqual(afterRuns,initialRuns,'Generating an inventory must not create or modify electrical runs');
    await page.getByText('Allocation assumptions & service audit',{exact:true}).click();
    await page.locator('#reset-view').click();
    await page.screenshot({path:path.join(__dirname,'..','runs','fleet-desktop.png'),fullPage:true});
    await page.reload();await page.waitForFunction(id=>fleet?.id===id,defaultFleet);
    await page.setViewportSize({width:390,height:844});
    await page.locator('#layer').selectOption('fleet');
    await page.screenshot({path:path.join(__dirname,'..','runs','fleet-mobile.png'),fullPage:true});
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1),false);
    assert.equal(await page.locator('#error').isVisible(),false);
    assert.deepEqual(errors,[]);
    console.log(JSON.stringify({passed:true,households:447,vehicles:751,defaultEVs:75,adoption20EVs:150,fixedEVs:500,evMapMarkers:markerCount,householdInspection:true,export:true,reloadRestored:true,electricalBaselineUnchanged:true,browserErrors:errors}));
  }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exit(1);});